# Explicá la diferencia entre include y extend:
# - Para métodos de instancia usá include.
# - Para métodos de clase usá extend.

# include mezcla los métodos del módulo como métodos de instancia: los va a tener cada objeto creado 
# con new de esa clase.
# extend incorpora los métodos del módulo al objeto receptor — cualquier objeto, no sólo una clase